import type {KeybindString} from "#lib/settings/types";
import {registry} from "#lib/settings/registry";
import type {HexColor} from "./colors";

const re = /^\s*([a-z-]+)[\s]*=\s*(.*)\s*$/;

const colors = ["background", "foreground", "cursor-color", "selection-background", "selection-foreground"];

// Keys Ghostty still accepts but no longer documents, mapped onto the registry entry that
// replaced them, so importing an older config keeps the value instead of silently dropping it.
export const LEGACY_KEYS: Record<string, string> = {
    "scrollback-limit": "scrollback-limit-bytes" // since 1.4.0, split into -bytes/-lines
};

export function parse(configString: string) {
    const lines = configString.split("\n");


    // Registry settings land on the flat string store; `palette` and `keybind` get their own shapes
    // on top of it, so the index signature has to allow them explicitly.
    const results: {palette: Array<HexColor | "">; keybind: KeybindString[]; [key: string]: string | string[]} = {
        palette: Array(256) as Array<HexColor | "">,
        keybind: [] as KeybindString[]
    };

    for (let p = 0; p < 256; p++) results.palette[p] = "";

    for (const l of lines) {
        const line = l.trim();
        const match = re.exec(line);
        if (!match) continue;
        const key = match[1].trim();
        const value = match[2].trim();

        if (key === "palette") {
            const split = value.split("=");
            const num = parseInt(split[0].trim());
            const color = split[1].trim() as HexColor; // TODO: perform validation
            if (num < 0 || num > 255) continue;
            results.palette[num] = color;
        }
        else {
            const resolvedKey = LEGACY_KEYS[key] ?? key;
            const split = resolvedKey.split("-");
            let newKey = split[0].trim();
            for (let s = 1; s < split.length; s++) {
                newKey += split[s].charAt(0).toUpperCase();
                newKey += split[s].substring(1);
            }

            const normalized = colors.includes(resolvedKey) && value.length === 6 && !value.startsWith("#")
                ? `#${value}`
                : value;

            // Repeatable settings (font-family, keybind, …) may appear on multiple lines;
            // accumulate them into an array rather than letting later lines overwrite earlier
            // ones. keybind needs no carveout here — it's just another `repeatable` key.
            const entry = registry[newKey as keyof typeof registry] as {repeatable?: boolean} | undefined;
            if (entry?.repeatable) {
                const existing = results[newKey];
                if (Array.isArray(existing)) existing.push(normalized);
                else results[newKey] = [normalized];
            }
            else {
                results[newKey] = normalized;
            }
        }
    }

    return results;
};

export default parse;


export const CONFIG_HEADER = ["# Config generated by Ghostty Config", "# https://github.com/NotoChen/ghostty-config", ""];

/** The `<key> = <value>` lines for one setting — one per element for a repeatable. */
export function settingLines(key: string, value: string | string[]): string[] {
    if (!Array.isArray(value)) return [`${key} = ${value}`];
    const lines: string[] = [];
    for (let i = 0; i < value.length; i++) {
        if (value[i] === undefined || value[i] === null) continue;
        lines.push(`${key} = ${value[i]}`);
    }
    return lines;
}

export function serialize(config: Record<string, string | string[]>, includeHeader = true) {
    const lines = includeHeader ? [...CONFIG_HEADER] : [];
    for (const [key, value] of Object.entries(config)) lines.push(...settingLines(key, value));

    return lines.join("\n");
}

