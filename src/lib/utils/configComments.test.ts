import {describe, expect, it} from "vitest";
import {annotatedConfigText, configAnnotations} from "./configComments";
import {parse} from "./parse";

// The generated config is read by a human before it is read by Ghostty, so these lock the two
// things that make it readable: a module header per section and a comment above every key —
// while proving the annotations still parse back to exactly the same values.

describe("annotatedConfigText()", () => {
    it("round-trips through parse()", () => {
        const source = {
            "font-size": "18",
            "bell-features": "system",
            "keybind": ["ctrl+a=select_all", "ctrl+d=new_split:right"]
        };
        const parsed = parse(annotatedConfigText(source));
        expect(parsed.fontSize).toBe("18");
        expect(parsed.bellFeatures).toBe("system");
        expect(parsed.keybind).toEqual(source.keybind);
    });

    it("writes each key once and annotates it", () => {
        const text = annotatedConfigText({"font-size": "18"});
        expect(text.match(/^font-size = 18$/gm)).toHaveLength(1);
        expect(text).toContain("# ========== ");
        const comment = configAnnotations().get("font-size")!.comment;
        expect(comment).toContain("字体大小");
        expect(text).toContain(`# ${comment}`);
    });

    it("puts keys that share a section under one header", () => {
        const text = annotatedConfigText({"font-family": ["JetBrains Mono"], "font-family-bold": ["JetBrains Mono Bold"]});
        const blocks = text.trimEnd().split("\n\n");
        const block = blocks.find(b => b.includes("font-family = JetBrains Mono"))!;
        expect(block).toContain("font-family-bold = JetBrains Mono Bold");
        expect(block.split("\n").filter(line => line.startsWith("# ====="))).toHaveLength(1);
        expect(blocks.filter(b => b.includes("font-family-bold"))).toHaveLength(1);
    });

    it("keeps the header when asked and drops it otherwise", () => {
        expect(annotatedConfigText({"font-size": "18"})).toMatch(/^# Config generated by Ghostty Config/);
        expect(annotatedConfigText({"font-size": "18"}, false).startsWith("# ========== ")).toBe(true);
    });

    it("keeps a key the navigation tree doesn't place", () => {
        expect(annotatedConfigText({"totally-unknown": "1"})).toContain("totally-unknown = 1");
    });

    it("ends with exactly one newline", () => {
        expect(annotatedConfigText({"font-size": "18"})).toMatch(/[^\n]\n$/);
        expect(annotatedConfigText({})).toMatch(/[^\n]\n$/);
    });
});
